"""Golden-vector and API-behaviour tests for pyspamsum.hash.

All golden values were generated with the untouched pure-Python reference
implementation (``pyspamsum/_pure.py``) and cross-checked against the
compiled Cython core.
"""
import random
import re

import pytest

import pyspamsum
from pyspamsum._pure import hash as reference_hash


def seeded_bytes(seed, size):
    """Deterministic pseudo-random bytes (stable across Python versions)."""
    rng = random.Random(seed)
    return bytes(rng.getrandbits(8) for _ in range(size))


HASH_RE = re.compile(r'^(\d+):([A-Za-z0-9+/]{0,64}):([A-Za-z0-9+/]{0,32})$')

# (label, input, expected hash) -- values generated by the reference
# implementation, cross-checked against the Cython core.
GOLDEN = [
    ('empty', b'', '3::'),
    ('one-byte', b'A', '3:k:k'),
    ('abc', b'abc', '3:uG:uG'),
    ('hello-world', b'hello world', '3:iKFSMPn:rJPn'),
    ('pangram', b'The quick brown fox jumps over the lazy dog',
     '3:FJKKIUKact:FHIGi'),
    ('zeros-1000', b'\x00' * 1000, '3::'),
    ('a-10000', b'a' * 10000, '3:tjl:X'),
    ('pattern-10240', bytes(range(256)) * 40,
     '192:znnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnnb:n'),
    ('random-4096', seeded_bytes(42, 4096),
     '96:VVwrp65gS6OdDGoOaNIRyCNvIDNqaf7oDhxz8PN2MXDosex2:'
     'jwV65V6OdDBOaNkyo2qafMbURXN'),
    ('random-200000', seeded_bytes(43, 200000),
     '6144:eoZeU/derv+yqhmL6gtZ2orvwI6axCQHO2x/zzblV6J:'
     'dcUy2y3L6gworvwI6UC8xbdVy'),
]


@pytest.mark.parametrize('label,data,expected', GOLDEN, ids=[g[0] for g in GOLDEN])
def test_golden_vectors(label, data, expected):
    assert pyspamsum.hash(data) == expected
    # the pure-Python oracle must still agree with the golden value
    assert reference_hash(data) == expected


def test_str_and_bytes_agree():
    assert (pyspamsum.hash('The quick brown fox jumps over the lazy dog')
            == pyspamsum.hash(b'The quick brown fox jumps over the lazy dog'))


def test_unicode_input_is_utf8_encoded():
    text = 'héllo wörld — ünïcode ☃'
    assert pyspamsum.hash(text) == reference_hash(text.encode('utf-8'))


@pytest.mark.parametrize('bad', [123, None, 4.5, [1, 2], {'a': 1}, bytearray(b'x')])
def test_hash_rejects_other_types(bad):
    with pytest.raises(TypeError):
        pyspamsum.hash(bad)


def test_empty_input():
    assert pyspamsum.hash(b'') == '3::'
    assert pyspamsum.hash('') == '3::'


@pytest.mark.parametrize('size', [0, 1, 2, 3, 64, 100, 1000, 65536])
def test_format_invariants(size):
    data = seeded_bytes(99, size)
    h = pyspamsum.hash(data)
    m = HASH_RE.match(h)
    assert m, 'hash does not match the blocksize:s1:s2 format: %r' % h
    bs = int(m.group(1))
    assert bs >= pyspamsum.BLOCKSIZE_MIN
    # block sizes are 3 * 2**k
    assert bs == pyspamsum.BLOCKSIZE_MIN or bs % (2 * pyspamsum.BLOCKSIZE_MIN) == 0
    assert bs * pyspamsum.SPAMSUM_LENGTH >= size


@pytest.mark.parametrize('size', [1000, 65536, 300000])
def test_half_length_or_min_block(size):
    # The retry loop stops when the primary hash string has reached at
    # least half the target length, or the minimum block size is hit.
    bs, s1, _s2 = pyspamsum.hash(seeded_bytes(123, size)).split(':')
    assert (len(s1) >= pyspamsum.SPAMSUM_LENGTH // 2
            or int(bs) == pyspamsum.BLOCKSIZE_MIN)


def test_deterministic():
    data = seeded_bytes(7, 12345)
    assert pyspamsum.hash(data) == pyspamsum.hash(data)


def test_public_constants():
    assert pyspamsum.BLOCKSIZE_MIN == 3
    assert pyspamsum.SPAMSUM_LENGTH == 64
